//! Renders the node catalog to `docs/parity-checklist.md`.

use crate::{Result, workspace_root};
use dms_engine::catalog::{NODES, Palette, Scope};
use dms_engine::nodes;
use std::fmt::Write as _;

const DOC: &str = "docs/parity-checklist.md";

pub fn run(check: bool) -> Result<()> {
    let path = workspace_root()?.join(DOC);
    let rendered = render();
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current.replace("\r\n", "\n") != rendered {
            return Err(format!("{DOC} is stale; run `cargo xtask parity`"));
        }
        println!("xtask parity: {DOC} up to date");
    } else {
        std::fs::write(&path, rendered).map_err(|e| format!("cannot write {DOC}: {e}"))?;
        println!("xtask parity: wrote {DOC}");
    }
    Ok(())
}

fn render() -> String {
    let mut out = String::new();
    // Writing to a String cannot fail.
    let _ = writeln!(out, "# Node parity checklist\n");
    let _ = writeln!(
        out,
        "> Generated by `cargo xtask parity` from `crates/catalog/src/lib.rs`. Do not edit.\n"
    );
    let _ = writeln!(
        out,
        "Status `done (statistical)`: trained to statistical, not exact, parity with Modeler (`docs/statistical-parity.md`).\n"
    );
    let _ = writeln!(out, "| Scope | Implemented | Total |\n|---|---|---|");
    for scope in [
        Scope::Mvp,
        Scope::Later,
        Scope::LicenseBlocked,
        Scope::OutOfScope,
    ] {
        let coverage = nodes::coverage(scope);
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            scope.label(),
            coverage.implemented,
            coverage.total
        );
    }
    for palette in Palette::ALL {
        let _ = writeln!(
            out,
            "\n## {}\n\n| Node | Id | Scope | Status | Modeler identifiers |\n|---|---|---|---|---|",
            palette.label()
        );
        for spec in NODES.iter().filter(|spec| spec.palette == palette) {
            let status = if nodes::is_statistical(spec.id) {
                "done (statistical)"
            } else if nodes::is_implemented(spec.id) {
                "done"
            } else {
                "missing"
            };
            let identifiers = if spec.modeler.is_empty() {
                "(unmapped)".to_string()
            } else {
                spec.modeler
                    .iter()
                    .map(|identifier| format!("`{identifier}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let _ = writeln!(
                out,
                "| {} | `{}` | {} | {} | {} |",
                spec.label.replace('|', "\\|"),
                spec.id,
                spec.scope.label(),
                status,
                identifiers
            );
        }
    }
    out
}
